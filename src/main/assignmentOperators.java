package main;

public class assignmentOperators {
    static void main(String[] args) {
        int x = 5;
        x += 3;// x= x+3
        System.out.println(x);
        x -= 3;
        System.out.println(x);
        x *= 3;
        System.out.println(x);
        x /= 3;
        //similiarlly for all arithmetic operator
        System.out.println(x);
        String name = "John";
        name += " Doe";// name = name + Doe
        System.out.println(name);
        double num = 3.14;
        num += 2;
        System.out.println(num);


    }
}
